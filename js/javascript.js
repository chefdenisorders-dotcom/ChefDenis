function getCurrentLanguage() {
  const urlLanguage = new URLSearchParams(window.location.search).get("lang");
  if (translations[urlLanguage]) {
    setCurrentLanguage(urlLanguage, false);
    return urlLanguage;
  }

  let storedLanguage = null;
  try {
    storedLanguage = localStorage.getItem("siteLanguage") || sessionStorage.getItem("siteLanguage");
  } catch (error) {
    storedLanguage = null;
  }

  return translations[storedLanguage] ? storedLanguage : "ro";
}

function setCurrentLanguage(language, updateUrl = true) {
  if (!translations[language]) return;
  try {
    localStorage.setItem("siteLanguage", language);
    sessionStorage.setItem("siteLanguage", language);
  } catch (error) {
    console.warn("Language storage is not available:", error);
  }

  if (updateUrl) {
    const url = new URL(window.location.href);
    url.searchParams.set("lang", language);
    window.history.replaceState({}, "", url);
  }
}

function syncLanguageLinks(language = getCurrentLanguage()) {
  $$("a[href]").forEach(link => {
    const href = link.getAttribute("href");
    if (!href || href.startsWith("#") || href.startsWith("tel:") || href.startsWith("mailto:") || /^(https?:)?\/\//i.test(href)) return;

    const [pathAndQuery, hash] = href.split("#");
    const [path, query = ""] = pathAndQuery.split("?");
    const params = new URLSearchParams(query);

    params.set("lang", language);
    link.setAttribute("href", `${path}?${params.toString()}${hash ? `#${hash}` : ""}`);
  });
}

function t(key) {
  const lang = getCurrentLanguage();
  return translations[lang]?.[key] || translations.ro[key] || key;
}

function getProductName(item) {
  const lang = getCurrentLanguage();
  return item.names?.[lang] || item.names?.ro || item.name || "";
}

function applyTranslations() {
  const lang = getCurrentLanguage();
  document.documentElement.lang = lang;

  $$("[data-i18n]").forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });

  $$("[data-i18n-placeholder]").forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });

  $$("[data-product-name]").forEach(el => {
    const [category, index] = el.dataset.productName.split(".");
    const item = productsData[category]?.[Number(index)];
    if (item) el.textContent = getProductName(item);
  });

  $$("option[data-ro][data-price]").forEach(option => {
    const name = option.dataset[lang] || option.dataset.ro;
    option.textContent = `${name} - ${option.dataset.price} MDL`;
  });

  const languageSelect = byId("language-select");
  if (languageSelect) languageSelect.value = lang;
  syncLanguageLinks(lang);
}

document.addEventListener("DOMContentLoaded", () => {
  const burger = $(".burger");
  const nav = $(".nav");
  const cartSidebar = byId("cart-sidebar");
  const cartList = byId("cart-list");
  const cartCount = byId("cart-count");
  const totalEl = byId("total");
  const checkoutBtn = byId("checkout-btn");
  const checkoutModal = byId("checkout-modal");
  const checkoutItems = byId("checkout-items");
  const checkoutTotal = byId("checkout-total");
  const closeCheckout = $(".close-checkout");
  const cancelBtn = byId("cancel-order");
  const confirmCheckout = byId("confirm-checkout");
  const languageSelect = byId("language-select");
  const checkoutFulfillment = byId("checkout-fulfillment");
  const checkoutCity = byId("checkout-city");
  const checkoutStreet = byId("checkout-street");
  const checkoutLocation = byId("checkout-location");

  applyTranslations();

  languageSelect?.addEventListener("change", () => {
    setCurrentLanguage(languageSelect.value);
    applyTranslations();
    updateCart();
    renderCheckoutItems();
    updateComboPreview();
  });

  window.addEventListener("storage", event => {
    if (event.key !== "siteLanguage") return;
    applyTranslations();
    updateCart();
    renderCheckoutItems();
    updateComboPreview();
  });

  function updateCheckoutFields() {
    const isDelivery = checkoutFulfillment?.value === "delivery";
    $$(".checkout-delivery-field").forEach(el => {
      el.style.display = isDelivery ? "block" : "none";
      if ("required" in el) el.required = isDelivery;
    });
    $$(".checkout-pickup-field").forEach(el => {
      el.style.display = isDelivery ? "none" : "block";
      if ("required" in el) el.required = !isDelivery;
    });
  }

  checkoutFulfillment?.addEventListener("change", updateCheckoutFields);
  checkoutLocation?.addEventListener("change", () => {
    if (!checkoutCity || !checkoutLocation?.value) return;
    if (checkoutLocation.value.includes("Chișinău")) checkoutCity.value = "Chișinău";
    if (checkoutLocation.value.includes("Ialoveni")) checkoutCity.value = "Ialoveni";
  });
  updateCheckoutFields();

  if (burger && nav) {
    burger.addEventListener("click", () => {
      nav.classList.toggle("active");
      burger.classList.toggle("active");
    });
  }

  $$(".nav a").forEach(link => {
    const linkPath = new URL(link.getAttribute("href"), window.location.href).pathname;
    if (linkPath === window.location.pathname) {
      link.classList.add("active");
      link.setAttribute("aria-current", "page");
    }

    link.addEventListener("click", () => {
      nav?.classList.remove("active");
      burger?.classList.remove("active");
    });
  });

  const header = $(".header");
  if (header) {
    window.addEventListener("scroll", () => {
      header.classList.toggle("scrolled", window.scrollY > 50);
    });
  }

  const revealElements = $$(".reveal, .menu-block");
  function revealOnScroll() {
    revealElements.forEach(el => {
      if (el.getBoundingClientRect().top < window.innerHeight - 100) {
        el.classList.add("active");
      }
    });
  }
  window.addEventListener("scroll", revealOnScroll);
  revealOnScroll();

  function closeProductBlock(block) {
    if (!block) return;
    const products = $(".products", block);
    const button = $(".toggle-products", block);
    if (!products || !button || !products.classList.contains("active")) {
      block?.classList.remove("active");
      button?.classList.remove("active");
      return;
    }

    products.classList.add("is-closing");
    button.classList.remove("active");
    block.classList.remove("active");

    window.setTimeout(() => {
      products.classList.remove("active", "is-closing");
    }, 500);
  }

  function closeOtherProductBlocks(activeBlock) {
    $$(".menu-block.active").forEach(block => {
      if (block !== activeBlock) closeProductBlock(block);
    });
  }

  function openProductBlock(block) {
    if (!block) return;
    const products = $(".products", block);
    const button = $(".toggle-products", block);
    if (!products || !button) return;

    closeOtherProductBlocks(block);

    products.classList.remove("is-closing");
    products.classList.add("active");
    button.classList.add("active");
    block.classList.add("active");
  }

  $$(".toggle-products").forEach(button => {
    button.addEventListener("click", () => {
      const block = button.closest(".menu-block");
      const products = block ? $(".products", block) : null;
      if (!block || !products) return;

      if (products.classList.contains("active")) {
        closeProductBlock(block);
      } else {
        openProductBlock(block);
      }
    });
  });

  $$(".menu-block").forEach(block => {
    block.addEventListener("click", event => {
      if (event.target.closest("button, a")) return;
      openProductBlock(block);
    });
  });

  $$(".menu-tabs a[href^='#']").forEach(link => {
    link.addEventListener("click", event => {
      const target = $(link.getAttribute("href"));
      if (!target) return;
      event.preventDefault();
      openProductBlock(target.classList.contains("menu-block") ? target : null);
      target.scrollIntoView({ behavior: "smooth", block: "start" });
    });
  });

  $$(".popular-card").forEach(card => {
    const summary = $("summary", card);
    if (!summary) return;

    summary.addEventListener("click", event => {
      event.preventDefault();

      if (card.classList.contains("is-closing")) return;

      if (card.open) {
        card.classList.remove("is-opening");
        card.classList.add("is-closing");

        window.setTimeout(() => {
          card.open = false;
          card.classList.remove("is-closing");
        }, 340);
      } else {
        card.open = true;
        card.classList.add("is-opening");
      }
    });
  });

  function getCart() {
    return JSON.parse(localStorage.getItem("cart")) || [];
  }

  function saveCart(cart) {
    localStorage.setItem("cart", JSON.stringify(cart));
  }

  function normalizeCartItem(item) {
    if (item.key && item.names) return item;

    const allProducts = Object.values(productsData).flat();
    const found = allProducts.find(product => product.names.ro === item.name || product.names.en === item.name || product.names.ru === item.name);
    return found || { key: item.name, price: item.price, names: { ro: item.name, en: item.name, ru: item.name } };
  }

  function groupCart(cart) {
    const grouped = {};
    cart.map(normalizeCartItem).forEach(item => {
      if (!grouped[item.key]) {
        grouped[item.key] = { ...item, qty: 1 };
      } else {
        grouped[item.key].qty++;
      }
    });
    return Object.values(grouped);
  }

  function calculateTotal(cart) {
    return cart.reduce((sum, item) => sum + Number(item.price || 0), 0);
  }

  function updateCart() {
    if (!cartList || !cartCount || !totalEl) return;

    const cart = getCart().map(normalizeCartItem);
    const grouped = groupCart(cart);

    cartList.innerHTML = "";
    let total = 0;

    grouped.forEach(item => {
      const li = document.createElement("li");
      const name = getProductName(item);

      li.innerHTML = `
        <div class="cart-left">
          <div class="cart-title">${name}</div>
          <div class="qty-box">
            <button onclick="changeQty('${item.key}', -1)">-</button>
            <span>${item.qty}</span>
            <button onclick="changeQty('${item.key}', 1)">+</button>
          </div>
        </div>
        <div class="cart-price">${item.price * item.qty} MDL</div>
      `;

      cartList.appendChild(li);
      total += item.price * item.qty;
    });

    cartCount.innerText = cart.length;
    totalEl.innerText = `${t("cart.total")}: ${total} MDL`;
  }

  function renderCheckoutItems() {
    if (!checkoutItems || !checkoutTotal) return;

    const cart = getCart().map(normalizeCartItem);
    const grouped = groupCart(cart);
    let total = 0;

    checkoutItems.innerHTML = "";

    grouped.forEach(item => {
      const li = document.createElement("li");
      li.innerHTML = `
        <div class="cart-left">
          <div class="cart-title">${getProductName(item)}</div>
          <span class="qty-static">${item.qty}x</span>
        </div>
        <div class="cart-price">${item.price * item.qty} MDL</div>
      `;
      checkoutItems.appendChild(li);
      total += item.price * item.qty;
    });

    checkoutTotal.textContent = `${t("cart.total")}: ${total} MDL`;
  }

  window.changeQty = function(key, change) {
    let cart = getCart().map(normalizeCartItem);

    if (change > 0) {
      const item = cart.find(i => i.key === key);
      if (item) cart.push(item);
    } else {
      const index = cart.findIndex(i => i.key === key);
      if (index !== -1) cart.splice(index, 1);
    }

    saveCart(cart);
    updateCart();
    renderCheckoutItems();
  };

  window.toggleCart = function() {
    cartSidebar?.classList.toggle("active");
    updateCart();
  };

  function showNotification(message, color = "#316c42") {
    const notif = document.createElement("div");
    notif.classList.add("notification");
    notif.style.background = color;
    notif.textContent = message;
    document.body.appendChild(notif);

    setTimeout(() => notif.classList.add("show"), 10);
    setTimeout(() => {
      notif.classList.remove("show");
      setTimeout(() => notif.remove(), 300);
    }, 3000);
  }

  function addItemToCart(item) {
    if (!item) return;
    const cart = getCart().map(normalizeCartItem);
    cart.push(item);
    saveCart(cart);
    updateCart();
    showNotification(t("cart.added"));
  }

  $$(".add-cart-btn").forEach(button => {
    button.addEventListener("click", () => {
      const category = button.dataset.category;
      const index = Number(button.dataset.index);
      addItemToCart(productsData[category]?.[index]);
    });
  });

  $$(".add-combo-btn").forEach(button => {
    button.addEventListener("click", () => {
      addItemToCart({
        key: button.dataset.comboKey,
        price: Number(button.dataset.comboPrice),
        names: {
          ro: button.dataset.comboRo,
          en: button.dataset.comboEn,
          ru: button.dataset.comboRu
        }
      });
    });
  });

  const comboFood = byId("combo-food");
  const comboDrink = byId("combo-drink");
  const comboImage = byId("combo-image");
  const comboOriginal = byId("combo-original");
  const comboDiscounted = byId("combo-discounted");
  const addCustomCombo = byId("add-custom-combo");

  function getSelectedComboOption(select) {
    return select?.selectedOptions?.[0] || null;
  }

  function getComboState() {
    const food = getSelectedComboOption(comboFood);
    const drink = getSelectedComboOption(comboDrink);
    if (!food || !drink) return null;

    const foodPrice = Number(food.dataset.price || 0);
    const drinkPrice = Number(drink.dataset.price || 0);
    const original = foodPrice + drinkPrice;
    const discounted = Math.round(original * 0.9);
    const lang = getCurrentLanguage();
    const foodName = food.dataset[lang] || food.dataset.ro || food.textContent.trim();
    const drinkName = drink.dataset[lang] || drink.dataset.ro || drink.textContent.trim();
    const image = food.dataset.image || "../images/sandwich.jpg";

    return { food, drink, original, discounted, foodName, drinkName, image };
  }

  function updateComboPreview() {
    const combo = getComboState();
    if (!combo) return;
    if (comboOriginal) comboOriginal.textContent = `${combo.original} MDL`;
    if (comboDiscounted) comboDiscounted.textContent = `${combo.discounted} MDL`;
    if (comboImage) {
      comboImage.src = combo.image;
      comboImage.alt = `Combo ${combo.foodName}`;
    }
  }

  comboFood?.addEventListener("change", updateComboPreview);
  comboDrink?.addEventListener("change", updateComboPreview);
  updateComboPreview();

  addCustomCombo?.addEventListener("click", () => {
    const combo = getComboState();
    if (!combo) return;

    addItemToCart({
      key: `combo.${combo.food.value}_${combo.drink.value}`,
      price: combo.discounted,
      names: {
        ro: `Combo ${combo.food.dataset.ro} + ${combo.drink.dataset.ro}`,
        en: `Combo ${combo.food.dataset.en || combo.food.dataset.ro} + ${combo.drink.dataset.en || combo.drink.dataset.ro}`,
        ru: `Комбо ${combo.food.dataset.ru || combo.food.dataset.ro} + ${combo.drink.dataset.ru || combo.drink.dataset.ro}`
      }
    });
  });

  checkoutBtn?.addEventListener("click", () => {
    const cart = getCart();
    if (!cart.length) return showNotification(t("cart.empty"), "#c0392b");

    renderCheckoutItems();
    if (checkoutModal) checkoutModal.style.display = "flex";
  });

  cancelBtn?.addEventListener("click", () => {
    const cart = getCart();
    if (!cart.length) return showNotification(t("cart.empty"), "#c0392b");

    localStorage.removeItem("cart");
    updateCart();
    if (checkoutModal) checkoutModal.style.display = "none";
    showNotification(t("cart.cancelled"), "#c0392b");
  });

  closeCheckout?.addEventListener("click", () => {
    if (checkoutModal) checkoutModal.style.display = "none";
  });

  window.addEventListener("click", e => {
    if (e.target === checkoutModal) checkoutModal.style.display = "none";
  });

  confirmCheckout?.addEventListener("click", () => {
    const email = byId("checkout-email")?.value.trim();
    const fulfillment = byId("checkout-fulfillment")?.value || "pickup";
    const city = byId("checkout-city")?.value;
    const street = byId("checkout-street")?.value.trim();
    const pickupLocation = byId("checkout-location")?.value;
    const comment = byId("checkout-comment")?.value.trim() || "-";

    if (!email) return showNotification(t("checkout.needEmail"), "#c0392b");
    if (!city) return showNotification(t("checkout.needCity"), "#c0392b");
    if (fulfillment === "delivery" && !street) return showNotification(t("checkout.needStreet"), "#c0392b");
    if (fulfillment === "pickup" && !pickupLocation) return showNotification(t("checkout.needLocation"), "#c0392b");

    const cart = getCart().map(normalizeCartItem);
    if (!cart.length) return showNotification(t("cart.empty"), "#c0392b");

    const grouped = groupCart(cart);
    const total = calculateTotal(cart);
    const productsSummary = grouped.map(item => `${getProductName(item)} x ${item.qty} - ${item.price * item.qty} MDL`).join("\n");
    const fulfillmentLabel = fulfillment === "delivery" ? t("checkout.delivery") : t("checkout.pickup");
    const location = fulfillment === "delivery" ? `${city} - ${street}` : pickupLocation;
    const orderId = `CD-${Date.now().toString(36).toUpperCase()}`;
    const orderItems = [
      "Confirmare comandă Chef Denis",
      "",
      `Email client: ${email}`,
      `Metodă: ${fulfillmentLabel}`,
      `Oraș: ${city}`,
      `Locație/Adresă: ${location}`,
      `Comentariu: ${comment}`,
      "",
      "Produse:",
      productsSummary,
      "",
      `Total: ${total} MDL`,
      `Cod comandă: ${orderId}`
    ].join("\n");

    const templateParams = {
      to_email: email,
      to_name: email.split("@")[0],
      phone: "-",
      pickup_location: location,
      fulfillment: fulfillmentLabel,
      city,
      delivery_address: fulfillment === "delivery" ? street : "-",
      customer_comment: comment,
      order_items: orderItems,
      order_total: `${total} MDL`,
      order_id: orderId
    };

    emailjs.send("service_gmxfrk6", "template_4npizju", templateParams, "euwpozbIhFNJwaNTd")
      .then(() => {
        showNotification(t("checkout.sent"));
        localStorage.removeItem("cart");
        cartSidebar?.classList.remove("active");
        if (checkoutModal) checkoutModal.style.display = "none";
        byId("checkout-form")?.reset();
        updateCheckoutFields();
        updateCart();
      })
      .catch(() => {
        showNotification(t("checkout.emailError"), "#c0392b");
      });
  });

  updateCart();
});

window.openLocations = function(city) {
  const popup = byId("locations-popup");
  if (!popup) return;

  popup.style.display = "flex";
  requestAnimationFrame(() => popup.classList.add("active"));

  $$(".city-locations").forEach(el => {
    el.style.display = "none";
  });

  const selected = byId(city);
  if (selected) selected.style.display = "block";
};

window.closeLocations = function() {
  const popup = byId("locations-popup");
  if (!popup) return;

  popup.classList.remove("active");
  setTimeout(() => {
    if (!popup.classList.contains("active")) popup.style.display = "none";
  }, 220);
};

window.addEventListener("click", function(e) {
  const popup = byId("locations-popup");
  if (e.target === popup) {
    window.closeLocations();
  }
});
